"""Export ArUco bit patterns and built-in template specs for the on-device engine.

    python scripts/export_mobile_assets.py   # writes ../lib/omr/generated.ts
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import cv2

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scantron_omr import default_registry  # noqa: E402

OUT = ROOT.parent / "lib" / "omr" / "generated.ts"


def main() -> None:
    reg = default_registry()
    templates = [t.raw for t in reg.all() if t.alignment.kind == "aruco"]
    ids = sorted({m["id"] for t in templates for m in t["alignment"]["markers"]})
    dic = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_100)
    bits = {}
    for i in ids:
        b = cv2.aruco.Dictionary.getBitsFromByteList(dic.bytesList[i : i + 1], 4)
        bits[i] = "".join(str(int(v)) for v in b.flatten())  # row-major, 1 = white
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// AUTO-GENERATED by backend/scripts/export_mobile_assets.py - do not edit.\n"
        "import type { TemplateSpec } from './types';\n\n"
        "/** DICT_4X4_100 inner bits (row-major, '1' = white) for the marker ids used by built-in sheets. */\n"
        f"export const ARUCO_4X4: Record<number, string> = {json.dumps(bits, indent=2)};\n\n"
        f"export const BUILTIN_TEMPLATES: TemplateSpec[] = {json.dumps(templates, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(templates)} templates, {len(ids)} markers)")


if __name__ == "__main__":
    main()
